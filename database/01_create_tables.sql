-- =============================================================================
-- 1. GIRISH_DEPARTMENTS  - master list of hospital specialties
-- =============================================================================
CREATE TABLE GIRISH_DEPARTMENTS (
    DEPT_ID             NUMBER
                        GENERATED BY DEFAULT ON NULL AS IDENTITY
                        CONSTRAINT PK_GIRISH_DEPARTMENTS PRIMARY KEY,
    DEPT_CODE           VARCHAR2(10)  NOT NULL,
    DEPT_NAME           VARCHAR2(100) NOT NULL,
    FLOOR_NO            NUMBER(3),
    IS_ACTIVE           CHAR(1)       DEFAULT 'Y' NOT NULL,
    CREATED_BY          VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
    CREATED_DATE        TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_UPDATED_BY     VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
    LAST_UPDATED_DATE   TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_GIRISH_DEPT_CODE   UNIQUE (DEPT_CODE),
    CONSTRAINT UK_GIRISH_DEPT_NAME   UNIQUE (DEPT_NAME),
    CONSTRAINT CK_GIRISH_DEPT_ACTIVE CHECK (IS_ACTIVE IN ('Y','N'))
);


-- =============================================================================
-- 2. GIRISH_DOCTORS  - doctor master profile, OPD fee, room, status
--    FK -> DEPARTMENTS (delete restricted: a department with doctors
--    cannot be removed)
-- =============================================================================
CREATE TABLE GIRISH_DOCTORS (
    DOCTOR_ID           NUMBER
                        GENERATED BY DEFAULT ON NULL AS IDENTITY
                        CONSTRAINT PK_GIRISH_DOCTORS PRIMARY KEY,
    DEPT_ID             NUMBER        NOT NULL,
    EMP_CODE            VARCHAR2(20)  NOT NULL,
    FULL_NAME           VARCHAR2(120) NOT NULL,
    QUALIFICATION       VARCHAR2(120),
    EMAIL               VARCHAR2(150) NOT NULL,
    PHONE               VARCHAR2(15),
    ROOM_NO             VARCHAR2(15),
    CONSULT_FEE         NUMBER(8,2)   NOT NULL,
    LANGUAGES           VARCHAR2(120),
    IS_ACTIVE           CHAR(1)       DEFAULT 'Y' NOT NULL,
    CREATED_BY          VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
    CREATED_DATE        TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_UPDATED_BY     VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
    LAST_UPDATED_DATE   TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_GIRISH_DOCTOR_EMP   UNIQUE (EMP_CODE),
    CONSTRAINT UK_GIRISH_DOCTOR_EMAIL UNIQUE (EMAIL),
    CONSTRAINT FK_GIRISH_DOC_DEPT
        FOREIGN KEY (DEPT_ID) REFERENCES GIRISH_DEPARTMENTS (DEPT_ID),
    CONSTRAINT CK_GIRISH_DOC_FEE      CHECK (CONSULT_FEE >= 0),
    CONSTRAINT CK_GIRISH_DOC_ACTIVE   CHECK (IS_ACTIVE IN ('Y','N'))
);


-- =============================================================================
-- 3. GIRISH_SLOT_TEMPLATES  - weekly consultation plan for a doctor
--    e.g. Dr. Sharma : Mon/Wed/Fri 09:00-13:00, 15 min per slot, 2 per slot
--    FK -> DOCTORS (cascade: a deleted doctor loses his templates)
-- =============================================================================
CREATE TABLE GIRISH_SLOT_TEMPLATES (
    TEMPLATE_ID         NUMBER
                        GENERATED BY DEFAULT ON NULL AS IDENTITY
                        CONSTRAINT PK_GIRISH_SLOT_TEMPLATES PRIMARY KEY,
    DOCTOR_ID           NUMBER       NOT NULL,
    DAY_OF_WEEK         NUMBER(1)    NOT NULL,
    START_TIME          VARCHAR2(5)  NOT NULL,
    END_TIME            VARCHAR2(5)  NOT NULL,
    SLOT_MINUTES        NUMBER(3)    DEFAULT 15 NOT NULL,
    MAX_PATIENTS        NUMBER(3)    DEFAULT 1  NOT NULL,
    EFFECTIVE_FROM      DATE         DEFAULT TRUNC(SYSDATE) NOT NULL,
    EFFECTIVE_TO        DATE,
    IS_ACTIVE           CHAR(1)      DEFAULT 'Y' NOT NULL,
    CREATED_BY          VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
    CREATED_DATE        TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_UPDATED_BY     VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
    LAST_UPDATED_DATE   TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_GIRISH_TPL_DOC_SLOT UNIQUE (DOCTOR_ID, DAY_OF_WEEK, START_TIME),
    CONSTRAINT FK_GIRISH_TPL_DOCTOR
        FOREIGN KEY (DOCTOR_ID) REFERENCES GIRISH_DOCTORS (DOCTOR_ID) ON DELETE CASCADE,
    CONSTRAINT CK_GIRISH_TPL_DOW      CHECK (DAY_OF_WEEK BETWEEN 1 AND 7),
    CONSTRAINT CK_GIRISH_TPL_TIME     CHECK (END_TIME > START_TIME),
    CONSTRAINT CK_GIRISH_TPL_MINUTES  CHECK (SLOT_MINUTES BETWEEN 5 AND 120),
    CONSTRAINT CK_GIRISH_TPL_CAP      CHECK (MAX_PATIENTS BETWEEN 1 AND 50),
    CONSTRAINT CK_GIRISH_TPL_RANGE    CHECK (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO >= EFFECTIVE_FROM),
    CONSTRAINT CK_GIRISH_TPL_ACTIVE   CHECK (IS_ACTIVE IN ('Y','N'))
);


-- =============================================================================
-- 4. GIRISH_SLOTS  - concrete dated slots generated from a template
--    e.g. 20-NOV-2026 09:00-09:15, max 2, booked 1, AVAILABLE
--    FK -> DOCTORS (cascade), TEMPLATE_ID (SET NULL so slots survive a
--          template edit/delete)
--    CURRENT_BOOKINGS = seats taken by active holds + confirmed bookings.
--    CK_GIRISH_SLOT_CAPACITY is the database-level last line of defence
--    against overbooking, independent of the PL/SQL lock.
-- =============================================================================
CREATE TABLE GIRISH_SLOTS (
    SLOT_ID             NUMBER
                        GENERATED BY DEFAULT ON NULL AS IDENTITY
                        CONSTRAINT PK_GIRISH_SLOTS PRIMARY KEY,
    DOCTOR_ID           NUMBER       NOT NULL,
    TEMPLATE_ID         NUMBER,
    SLOT_DATE           DATE         NOT NULL,
    START_TIME          VARCHAR2(5)  NOT NULL,
    END_TIME            VARCHAR2(5)  NOT NULL,
    MAX_CAPACITY        NUMBER(3)    DEFAULT 1 NOT NULL,
    CURRENT_BOOKINGS    NUMBER(3)    DEFAULT 0 NOT NULL,
    STATUS              VARCHAR2(10) DEFAULT 'AVAILABLE' NOT NULL,
    CREATED_BY          VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
    CREATED_DATE        TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_UPDATED_BY     VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
    LAST_UPDATED_DATE   TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_GIRISH_SLOT_DOC_TIME UNIQUE (DOCTOR_ID, SLOT_DATE, START_TIME),
    CONSTRAINT FK_GIRISH_SLOT_DOCTOR
        FOREIGN KEY (DOCTOR_ID) REFERENCES GIRISH_DOCTORS (DOCTOR_ID) ON DELETE CASCADE,
    CONSTRAINT FK_GIRISH_SLOT_TPL
        FOREIGN KEY (TEMPLATE_ID) REFERENCES GIRISH_SLOT_TEMPLATES (TEMPLATE_ID) ON DELETE SET NULL,
    CONSTRAINT CK_GIRISH_SLOT_STATUS   CHECK (STATUS IN ('AVAILABLE','BOOKED','BLOCKED')),
    CONSTRAINT CK_GIRISH_SLOT_TIME     CHECK (END_TIME > START_TIME),
    CONSTRAINT CK_GIRISH_SLOT_CAPACITY CHECK (CURRENT_BOOKINGS BETWEEN 0 AND MAX_CAPACITY),
    CONSTRAINT CK_GIRISH_SLOT_MAX      CHECK (MAX_CAPACITY BETWEEN 1 AND 50)
);


-- =============================================================================
-- 5. GIRISH_PATIENTS  - patient master (UHID = hospital medical record no.)
-- =============================================================================
CREATE TABLE GIRISH_PATIENTS (
    PATIENT_ID          NUMBER
                        GENERATED BY DEFAULT ON NULL AS IDENTITY
                        CONSTRAINT PK_GIRISH_PATIENTS PRIMARY KEY,
    UHID                VARCHAR2(20)  NOT NULL,
    FULL_NAME           VARCHAR2(120) NOT NULL,
    DOB                 DATE,
    GENDER              CHAR(1)       NOT NULL,
    PHONE               VARCHAR2(15)  NOT NULL,
    EMAIL               VARCHAR2(150),
    BLOOD_GROUP         VARCHAR2(3),
    ADDRESS             VARCHAR2(400),
    IS_ACTIVE           CHAR(1)       DEFAULT 'Y' NOT NULL,
    CREATED_BY          VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
    CREATED_DATE        TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_UPDATED_BY     VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
    LAST_UPDATED_DATE   TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_GIRISH_PATIENT_UHID  UNIQUE (UHID),
    CONSTRAINT UK_GIRISH_PATIENT_PHONE UNIQUE (PHONE),
    CONSTRAINT CK_GIRISH_PAT_GENDER    CHECK (GENDER IN ('M','F','O')),
    CONSTRAINT CK_GIRISH_PAT_BLOOD     CHECK (BLOOD_GROUP IS NULL OR
                                              BLOOD_GROUP IN ('A+','A-','B+','B-','AB+','AB-','O+','O-')),
    CONSTRAINT CK_GIRISH_PAT_ACTIVE    CHECK (IS_ACTIVE IN ('Y','N'))
);


-- =============================================================================
-- 6. GIRISH_APPOINTMENTS  - core transaction: patient x slot, with lifecycle
--    HELD -> CONFIRMED -> CHECKED_IN -> COMPLETED
--                    \-> CANCELLED / NO_SHOW / EXPIRED
--    CONSULT_FEE is a frozen snapshot of the price at booking time.
-- =============================================================================
CREATE TABLE GIRISH_APPOINTMENTS (
    APPOINTMENT_ID      NUMBER
                        GENERATED BY DEFAULT ON NULL AS IDENTITY
                        CONSTRAINT PK_GIRISH_APPOINTMENTS PRIMARY KEY,
    BOOKING_REF         VARCHAR2(20) NOT NULL,
    SLOT_ID             NUMBER       NOT NULL,
    PATIENT_ID          NUMBER       NOT NULL,
    STATUS              VARCHAR2(12) DEFAULT 'HELD' NOT NULL,
    CONSULT_FEE         NUMBER(8,2),
    BOOKED_AT           TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    HOLD_EXPIRES_AT     TIMESTAMP(6),
    CONFIRMED_AT        TIMESTAMP(6),
    CHECKED_IN_AT       TIMESTAMP(6),
    COMPLETED_AT        TIMESTAMP(6),
    CANCELLED_AT        TIMESTAMP(6),
    CANCEL_REASON       VARCHAR2(400),
    CREATED_BY          VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
    CREATED_DATE        TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_UPDATED_BY     VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
    LAST_UPDATED_DATE   TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_GIRISH_APPT_REF     UNIQUE (BOOKING_REF),
    CONSTRAINT FK_GIRISH_APPT_SLOT
        FOREIGN KEY (SLOT_ID) REFERENCES GIRISH_SLOTS (SLOT_ID),
    CONSTRAINT FK_GIRISH_APPT_PATIENT
        FOREIGN KEY (PATIENT_ID) REFERENCES GIRISH_PATIENTS (PATIENT_ID),
    CONSTRAINT CK_GIRISH_APPT_STATUS  CHECK (STATUS IN ('HELD','CONFIRMED','CHECKED_IN',
                                                       'COMPLETED','CANCELLED','NO_SHOW','EXPIRED')),
    CONSTRAINT CK_GIRISH_APPT_HOLD    CHECK (STATUS <> 'HELD' OR HOLD_EXPIRES_AT IS NOT NULL),
    CONSTRAINT CK_GIRISH_APPT_FEE     CHECK (CONSULT_FEE IS NULL OR CONSULT_FEE >= 0)
);


-- =============================================================================
-- 7. GIRISH_TOKEN_QUEUE  - daily physical queue token, one per visit
--    UNIQUE (APPOINTMENT_ID) makes check-in idempotent (double-click safe)
--    UNIQUE (DOCTOR_ID, TOKEN_DATE, TOKEN_NO) keeps the daily token series clean
-- =============================================================================
CREATE TABLE GIRISH_TOKEN_QUEUE (
    TOKEN_ID            NUMBER
                        GENERATED BY DEFAULT ON NULL AS IDENTITY
                        CONSTRAINT PK_GIRISH_TOKEN_QUEUE PRIMARY KEY,
    APPOINTMENT_ID      NUMBER      NOT NULL,
    DOCTOR_ID           NUMBER      NOT NULL,
    TOKEN_DATE          DATE        DEFAULT TRUNC(SYSDATE) NOT NULL,
    TOKEN_NO            VARCHAR2(12) NOT NULL,
    QUEUE_STATUS        VARCHAR2(10) DEFAULT 'WAITING' NOT NULL,
    CALLED_AT           TIMESTAMP(6),
    CREATED_BY          VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
    CREATED_DATE        TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_UPDATED_BY     VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
    LAST_UPDATED_DATE   TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_GIRISH_TOKEN_APPT   UNIQUE (APPOINTMENT_ID),
    CONSTRAINT UK_GIRISH_TOKEN_NO     UNIQUE (DOCTOR_ID, TOKEN_DATE, TOKEN_NO),
    CONSTRAINT FK_GIRISH_TOKEN_APPT
        FOREIGN KEY (APPOINTMENT_ID) REFERENCES GIRISH_APPOINTMENTS (APPOINTMENT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_GIRISH_TOKEN_DOCTOR
        FOREIGN KEY (DOCTOR_ID) REFERENCES GIRISH_DOCTORS (DOCTOR_ID) ON DELETE CASCADE,
    CONSTRAINT CK_GIRISH_TOKEN_STATUS CHECK (QUEUE_STATUS IN ('WAITING','CALLED','DONE','SKIPPED'))
);


-- =============================================================================
-- 8. GIRISH_PAYMENTS  - append-only money ledger (simulated gateway)
--    CHARGE row on confirm, REFUND row (if any) on cancellation
-- =============================================================================
CREATE TABLE GIRISH_PAYMENTS (
    PAYMENT_ID          NUMBER
                        GENERATED BY DEFAULT ON NULL AS IDENTITY
                        CONSTRAINT PK_GIRISH_PAYMENTS PRIMARY KEY,
    APPOINTMENT_ID      NUMBER       NOT NULL,
    ENTRY_TYPE          VARCHAR2(10) DEFAULT 'CHARGE' NOT NULL,
    PAYMENT_MODE        VARCHAR2(10) NOT NULL,
    TXN_REF             VARCHAR2(40),
    AMOUNT              NUMBER(8,2)  NOT NULL,
    STATUS              VARCHAR2(10) DEFAULT 'SUCCESS' NOT NULL,
    PAID_AT             TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY          VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
    CREATED_DATE        TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_UPDATED_BY     VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
    LAST_UPDATED_DATE   TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_GIRISH_PAY_TXN      UNIQUE (TXN_REF),
    CONSTRAINT FK_GIRISH_PAY_APPT
        FOREIGN KEY (APPOINTMENT_ID) REFERENCES GIRISH_APPOINTMENTS (APPOINTMENT_ID) ON DELETE CASCADE,
    CONSTRAINT CK_GIRISH_PAY_TYPE     CHECK (ENTRY_TYPE IN ('CHARGE','REFUND')),
    CONSTRAINT CK_GIRISH_PAY_MODE     CHECK (PAYMENT_MODE IN ('UPI','CARD','CASH','NETBANKING','WALLET')),
    CONSTRAINT CK_GIRISH_PAY_STATUS   CHECK (STATUS IN ('SUCCESS','REFUNDED','FAILED','PENDING')),
    CONSTRAINT CK_GIRISH_PAY_AMOUNT   CHECK (AMOUNT > 0)
);


-- =============================================================================
-- 9. GIRISH_CANCELLATION_RULES  - refund policy as DATA, not code
--    Band matched on hours before slot start: MIN <= hours < MAX
--    (MAX_HOURS_BEFORE NULL = open ended top band)
-- =============================================================================
CREATE TABLE GIRISH_CANCELLATION_RULES (
    RULE_ID             NUMBER
                        GENERATED BY DEFAULT ON NULL AS IDENTITY
                        CONSTRAINT PK_GIRISH_CANCEL_RULES PRIMARY KEY,
    RULE_NAME           VARCHAR2(100) NOT NULL,
    MIN_HOURS_BEFORE    NUMBER(6,2)   NOT NULL,
    MAX_HOURS_BEFORE    NUMBER(6,2),
    REFUND_PERCENT      NUMBER(5,2)   NOT NULL,
    PENALTY_AMOUNT      NUMBER(8,2)   DEFAULT 0 NOT NULL,
    IS_ACTIVE           CHAR(1)       DEFAULT 'Y' NOT NULL,
    CREATED_BY          VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
    CREATED_DATE        TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_UPDATED_BY     VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
    LAST_UPDATED_DATE   TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_GIRISH_RULE_NAME    UNIQUE (RULE_NAME),
    CONSTRAINT CK_GIRISH_RULE_HOURS   CHECK (MIN_HOURS_BEFORE >= 0 AND
                                             (MAX_HOURS_BEFORE IS NULL OR
                                              MAX_HOURS_BEFORE > MIN_HOURS_BEFORE)),
    CONSTRAINT CK_GIRISH_RULE_REFUND  CHECK (REFUND_PERCENT BETWEEN 0 AND 100),
    CONSTRAINT CK_GIRISH_RULE_PENALTY CHECK (PENALTY_AMOUNT >= 0),
    CONSTRAINT CK_GIRISH_RULE_ACTIVE  CHECK (IS_ACTIVE IN ('Y','N'))
);


-- =============================================================================
-- 10. GIRISH_ERROR_LOG  - written by LOG_ERROR (autonomous transaction)
--     No IS_ACTIVE / audit columns: rows are immutable diagnostics, and
--     LOGGED_BY + LOGGED_AT already are the WHO columns.
-- =============================================================================
CREATE TABLE GIRISH_ERROR_LOG (
    ERROR_ID            NUMBER
                        GENERATED BY DEFAULT ON NULL AS IDENTITY
                        CONSTRAINT PK_GIRISH_ERROR_LOG PRIMARY KEY,
    MODULE_NAME         VARCHAR2(100) NOT NULL,
    ERROR_CODE          VARCHAR2(20),
    ERROR_MESSAGE       VARCHAR2(4000),
    BACKTRACE           CLOB,
    LOGGED_BY           VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
    LOGGED_AT           TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL
);


-- =============================================================================
-- SECONDARY INDEXES  (supporting the hot queries of the app)
--   unique constraints above already create their own indexes
-- =============================================================================
-- availability lookup (the most frequent query in the whole app)
CREATE INDEX IX_GIRISH_SLOT_DOC_DATE ON GIRISH_SLOTS (DOCTOR_ID, SLOT_DATE, STATUS);

-- no-show sweep / hold-expiry sweep
CREATE INDEX IX_GIRISH_SLOT_DATE_ST  ON GIRISH_SLOTS (SLOT_DATE, STATUS);

-- "My Bookings" page + patient history
CREATE INDEX IX_GIRISH_APPT_PATIENT  ON GIRISH_APPOINTMENTS (PATIENT_ID, BOOKED_AT DESC);

-- appointment status transitions (confirm / check-in / sweep)
CREATE INDEX IX_GIRISH_APPT_STATUS   ON GIRISH_APPOINTMENTS (STATUS, BOOKED_AT);

-- expired-hold sweep
CREATE INDEX IX_GIRISH_APPT_HOLD     ON GIRISH_APPOINTMENTS (STATUS, HOLD_EXPIRES_AT);

-- FK index (Oracle does not create one automatically) - also speeds up locking
CREATE INDEX IX_GIRISH_APPT_SLOT     ON GIRISH_APPOINTMENTS (SLOT_ID);

-- doctor's live queue for today
CREATE INDEX IX_GIRISH_TOKEN_DOC_DT  ON GIRISH_TOKEN_QUEUE (DOCTOR_ID, TOKEN_DATE, QUEUE_STATUS);

-- slip / receipt lookup
CREATE INDEX IX_GIRISH_PAY_APPT      ON GIRISH_PAYMENTS (APPOINTMENT_ID, ENTRY_TYPE);

-- department doctor list + doctor search by name
CREATE INDEX IX_GIRISH_DOC_DEPT      ON GIRISH_DOCTORS (DEPT_ID, IS_ACTIVE);
CREATE INDEX IX_GIRISH_DOC_NAME      ON GIRISH_DOCTORS (UPPER(FULL_NAME));


