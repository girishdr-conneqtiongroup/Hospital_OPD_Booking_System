--    (All statements are plain DDL/DML, so nothing needs a "/" terminator.
--     Run once. On a re-run you will get ORA-00955 "name is already used" -
--     drop with FILE 00 first if you want a clean rebuild.)
--
--  STANDARDS APPLIED
--    * GIRISH_ prefix on every object, upper case, <= 30 char names
--    * surrogate PK = identity column (GENERATED BY DEFAULT ON NULL)
--    * named constraints : PK_ / UK_ / CK_ / FK_  + table short name
--    * WHO audit columns on every business table, with DEFAULTs so no
--      INSERT can ever forget them
--    * soft delete via IS_ACTIVE, never DELETE on master data
--    * business rules (refund bands) stored as rows, not hard-coded
--    * 3NF : APPOINTMENTS stores SLOT_ID + PATIENT_ID only; the doctor is
--      reached through SLOTS.DOCTOR_ID, so no transitive dependency exists
-- -----------------------------------------------------------------------------
--  CREATE ORDER (parents first)
--    1 DEPARTMENTS   2 DOCTORS   3 SLOT_TEMPLATES   4 SLOTS   5 PATIENTS
--    6 APPOINTMENTS  7 TOKEN_QUEUE  8 PAYMENTS  9 CANCELLATION_RULES
--   10 ERROR_LOG
